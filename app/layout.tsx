/* --------------------------------------------------------------------------
   Fonts — self-hosted at build time by next/font. No request ever leaves the
   user's browser for a font file, and there is no layout shift on load.
   -------------------------------------------------------------------------- */

const newsreader = Newsreader({
  subsets: ["latin"],
  style: ["normal", "italic"],
  display: "swap",
  variable: "--font-newsreader",
  // Variable font: the full weight range ships in one file.
});

const karla = Karla({
  subsets: ["latin"],
  style: ["normal", "italic"],
  display: "swap",
  variable: "--font-karla",
});

