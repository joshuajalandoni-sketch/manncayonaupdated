export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang="en-PH"
      className={`${newsreader.variable} ${karla.variable}`}
      suppressHydrationWarning
    >
      <head>
        {/* Scroll reveals ship their hidden state in the SSR HTML. Without JS
            that would leave the Process essay blank, so unwind it: reveal the
            content and drop the weave veils entirely. Author !important beats
            a non-important inline style. */}
        <noscript>
          <style>{`#process [style*="opacity"]{opacity:1!important;transform:none!important}#process .motion-veil{display:none!important}`}</style>
        </noscript>
      </head>
      <body className="flex min-h-dvh flex-col bg-background font-sans text-ink">
        <SiteNav />
        <main id="main" className="flex-1">
          {children}
        </main>
        <SiteFooter />
        <script
          type="application/ld+json"
          // Static, author-controlled object — no user input reaches this.
          dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
        />
      </body>
    </html>
  );
}
